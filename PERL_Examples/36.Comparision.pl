#!/usr/bin/perl 

$x = 15;
$y = 20;

if($x==$y)
{
	print"$x and $y are equal \n";
}
if($x!=$y)
{
	print"$x and $y are not equal \n";
}
if($x<$y) 
{
	print "$x is less than $y \n";
}
if($x>$y)
{
	print"$x is greater than to $y \n";
}
if($x<=$y)
{
	print("$x is less than or equal to $y \n");
}
if($x>=$y)
{
	print"$x is greater than or equal to $y \n";
}

